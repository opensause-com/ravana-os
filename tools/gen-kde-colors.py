#!/usr/bin/env python3
"""Generate Ravana OS KDE color schemes from one palette.

    python3 tools/gen-kde-colors.py   # writes system_files/usr/share/color-schemes/*.colors

All text/background pairs were checked for WCAG AA (>= 4.5:1).
"""
from pathlib import Path

BRAND = {
    "red": "#D21F3C",       # accent fill: buttons, selection, focus (white text 5.25:1)
    "red_deep": "#A50E25",  # pressed / inactive selection
}

SCHEMES = {
    "RavanaDark": {
        "name": "Ravana Dark",
        "view": "#0C0C0E", "view_alt": "#141417",
        "window": "#121214", "window_alt": "#17171A",
        "button": "#1C1C20", "button_alt": "#222227",
        "header": "#0E0E10", "tooltip": "#1C1C20",
        "text": "#F5F5F7", "muted": "#A1A1AA",
        "link": "#FF5A66", "visited": "#E07A9A",
        "hover": "#FF5A66", "focus": BRAND["red"],
        "positive": "#3FB950", "neutral": "#F2A93B", "negative": "#FF7B72",
        "sel": BRAND["red"], "sel_alt": BRAND["red_deep"], "sel_text": "#FFFFFF",
        "contrast": 4,
    },
    "RavanaLight": {
        "name": "Ravana Light",
        "view": "#FFFFFF", "view_alt": "#F7F7F8",
        "window": "#F4F4F5", "window_alt": "#EDEDEF",
        "button": "#FAFAFA", "button_alt": "#F0F0F2",
        "header": "#EDEDEF", "tooltip": "#FFFFFF",
        "text": "#18181B", "muted": "#52525B",
        "link": "#C8102E", "visited": "#8E1B5A",
        "hover": "#E0313E", "focus": BRAND["red"],
        "positive": "#1A7F37", "neutral": "#9A6700", "negative": "#B42318",
        "sel": BRAND["red"], "sel_alt": BRAND["red_deep"], "sel_text": "#FFFFFF",
        "contrast": 4,
    },
}


def rgb(h: str) -> str:
    h = h.lstrip("#")
    return ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def group(p, bg, bg_alt, fg="text", fg_inactive="muted", active=None):
    return {
        "BackgroundNormal": p[bg], "BackgroundAlternate": p[bg_alt],
        "DecorationFocus": p["focus"], "DecorationHover": p["hover"],
        "ForegroundNormal": p[fg], "ForegroundInactive": p[fg_inactive],
        "ForegroundActive": p[active] if active else p["hover"],
        "ForegroundLink": p["link"], "ForegroundVisited": p["visited"],
        "ForegroundPositive": p["positive"], "ForegroundNeutral": p["neutral"],
        "ForegroundNegative": p["negative"],
    }


def build(key: str, p: dict) -> str:
    sel = group(p, "sel", "sel_alt", fg="sel_text", fg_inactive="sel_text", active="sel_text")
    sel.update(ForegroundLink="#FFFFFF", ForegroundVisited="#FFE4E8")
    groups = {
        "Colors:Window": group(p, "window", "window_alt"),
        "Colors:View": group(p, "view", "view_alt"),
        "Colors:Button": group(p, "button", "button_alt"),
        "Colors:Header": group(p, "header", "window_alt"),
        "Colors:Header][Inactive": group(p, "header", "window_alt"),
        "Colors:Tooltip": group(p, "tooltip", "window_alt"),
        "Colors:Complementary": group(SCHEMES["RavanaDark"], "window", "window_alt"),
        "Colors:Selection": sel,
    }
    out = [
        "# Generated by tools/gen-kde-colors.py — edit the palette there, not here.",
        "[ColorEffects:Disabled]", "Color=56,56,56", "ColorAmount=0", "ColorEffect=0",
        "ContrastAmount=0.65", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", "",
        "[ColorEffects:Inactive]", "ChangeSelectionColor=true", "Color=112,111,110",
        "ColorAmount=0.025", "ColorEffect=2", "ContrastAmount=0.1", "ContrastEffect=2",
        "Enable=false", "IntensityAmount=0", "IntensityEffect=0", "",
    ]
    for name, vals in groups.items():
        out.append(f"[{name}]")
        out += [f"{k}={rgb(v)}" for k, v in sorted(vals.items())]
        out.append("")
    out += [
        "[General]", f"ColorScheme={key}", f"Name={p['name']}", "shadeSortColumn=true", "",
        "[KDE]", f"contrast={p['contrast']}", "",
        "[WM]",
        f"activeBackground={rgb(p['header'])}", f"activeBlend={rgb(p['text'])}",
        f"activeForeground={rgb(p['text'])}",
        f"inactiveBackground={rgb(p['header'])}", f"inactiveBlend={rgb(p['muted'])}",
        f"inactiveForeground={rgb(p['muted'])}", "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    dest = Path(__file__).resolve().parent.parent / "system_files/usr/share/color-schemes"
    dest.mkdir(parents=True, exist_ok=True)
    for key, palette in SCHEMES.items():
        (dest / f"{key}.colors").write_text(build(key, palette))
        print("wrote", dest / f"{key}.colors")
