#!/usr/bin/env bash
#
# Ravana OS live ISO: installer and live-session setup.
# Adapted from ublue-os/titanoboa examples/bazzite (Apache-2.0).

set -exo pipefail

source /etc/os-release

# Remove all versionlocks, in order to avoid dependency issues
dnf -qy versionlock clear

# Install Anaconda
# Firefox (RPM) hosts the Anaconda Web UI
dnf install -qy --allowerasing firefox anaconda-live libblockdev-{btrfs,lvm,dm}

mkdir -p /var/lib/rpm-state # Needed for Anaconda Web UI

# Utilities for displaying a dialog prompting users to review secure boot documentation
dnf install -qy --setopt=install_weak_deps=0 qrencode yad

# Variables
imageref="${RAVANA_IMAGE:?}"   # e.g. ghcr.io/ravana-os/ravana-os
imagetag="${RAVANA_TAG:?}"     # latest or testing"
sbkey='https://github.com/ublue-os/akmods/raw/main/certs/public_key.der'
SECUREBOOT_KEY="/usr/share/ublue-os/sb_pubkey.der"
SECUREBOOT_DOC_URL="https://github.com/ravana-os/ravana-os#secure-boot"
SECUREBOOT_DOC_URL_QR="/usr/share/ublue-os/secure_boot_qr.png"

# Ravana anaconda profile (os-release ID stays "bazzite" for upstream tooling)
: ${VARIANT_ID:?}
cat >/etc/anaconda/profile.d/ravana.conf <<EOF
# Anaconda configuration file for Ravana OS

[Profile]
profile_id = ravana

[Profile Detection]
